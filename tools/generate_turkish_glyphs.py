"""Generate the optional Classic font supplement from JetBrains Mono Bold v2.304."""

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


FONT_SHA256 = "5590990c82e097397517f275f430af4546e1c45cff408bde4255dad142479dcb"
GLYPHS = "ĞğİıŞşÇçÖöÜü"
# Cell sizes and baselines used by the pinned RadioFoundry JetBrains Mono fonts.
FACES = ((6, 12, 9), (8, 16, 12), (9, 18, 14), (12, 24, 19), (16, 32, 26))


def pack_glyph(font, width, height, baseline, char):
    # Render with room above and below the cell so marks can be shifted into view.
    image = Image.new("L", (width, height * 3))
    ImageDraw.Draw(image).text((0, baseline + height), char, font=font, fill=255, anchor="ls")
    rows = []
    for y in range(image.height):
        row = bytearray((width + 3) // 4)
        for x in range(width):
            coverage = (image.getpixel((x, y)) * 3 + 127) // 255
            row[x // 4] |= coverage << (6 - (x % 4) * 2)
        rows.append(row)
    inked = [y for y, row in enumerate(rows) if any(row)]
    first, last = inked[0], inked[-1]
    count = last - first + 1
    if count > height:
        raise ValueError(f"U+{ord(char):04X} exceeds the {width}x{height} font cell")
    top = min(max(first - height, 0), height - count)
    return bytes((top, count)) + b"".join(rows[first:last + 1])


def generate(font_path, license_path):
    probe = ImageFont.truetype(str(font_path), 100)
    lines = [
        "// SPDX-License-Identifier: OFL-1.1",
        "// Generated by tools/generate_turkish_glyphs.py from JetBrains Mono Bold v2.304.",
        "// Source: https://github.com/JetBrains/JetBrainsMono/releases/tag/v2.304",
        f"// Font SHA-256: {FONT_SHA256}",
        f"// FreeType: {ImageFont.core.freetype2_version}",
        "//",
        *(("// " + line).rstrip() for line in license_path.read_text(encoding="utf-8").splitlines()),
        "",
    ]
    for width, height, baseline in FACES:
        name = f"turkish_{width}x{height}"
        font = ImageFont.truetype(str(font_path), width * 100 / probe.getlength("0"))
        switch = {9: "CONFIG_FONT_BIG", 16: "CONFIG_FONT_XL"}.get(width)
        if switch:
            lines.append(f"#if {switch}")
        lines.append(f"static const uint8_t {name}_bits[] = {{")
        offsets = []
        offset = 0
        for char in GLYPHS:
            offsets.append(offset)
            glyph = pack_glyph(font, width, height, baseline, char)
            offset += len(glyph)
            pixels = ", ".join(f"0x{value:02x}" for value in glyph)
            lines.append(f"    {pixels}, // U+{ord(char):04X}")
        lines.extend(["};", f"static const uint16_t {name}_index[] = {{",
                      "    " + ", ".join(str(value) for value in offsets) + ",", "};"])
        if switch:
            lines.append("#endif")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("license", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != FONT_SHA256:
        parser.error("expected JetBrainsMono-Bold.ttf from v2.304")
    args.output.write_bytes(generate(args.font, args.license).encode("utf-8"))


if __name__ == "__main__":
    main()
